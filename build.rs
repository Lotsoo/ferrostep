//! Build script:
//! - copies the optional private welcome letter (`private/surat.txt`, never
//!   committed) into the build, so only builds made on the owner's machine
//!   contain it;
//! - converts the optional private gift media (`private/terompet.*`,
//!   `private/video/*.mp4`, never committed) with ffmpeg into frames + audio
//!   that the app embeds (see `src/ui/gift.rs`);
//! - on Windows targets, embeds the app icon and version info into
//!   `ferrostep.exe` so Explorer, the taskbar, shortcuts and "Apps" show the
//!   Ferrostep icon and name.

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    embed_letter();
    embed_gift_media();
    println!("cargo:rerun-if-changed=assets/icons/ferrostep.ico");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    let mut res = winresource::WindowsResource::new();
    res.set_icon("assets/icons/ferrostep.ico")
        .set("ProductName", "Ferrostep")
        .set("FileDescription", "Ferrostep")
        .set("CompanyName", "Ferrostep")
        .set("LegalCopyright", "MIT License");
    // Cross-compiling from Linux with the MinGW toolchain.
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("gnu") && !cfg!(windows) {
        res.set_toolkit_path("/usr/bin")
            .set_windres_path("x86_64-w64-mingw32-windres")
            .set_ar_path("x86_64-w64-mingw32-ar");
    }
    if let Err(e) = res.compile() {
        // A missing icon must not break the build; the exe just has no icon.
        println!("cargo:warning=could not embed the Windows icon: {e}");
    }
}

/// Writes the letter (or an empty file) to `$OUT_DIR/letter.txt`. Only
/// rewrites when the content changed, so normal builds stay incremental.
fn embed_letter() {
    let source = Path::new("private/surat.txt");
    println!("cargo:rerun-if-changed=private");
    println!("cargo:rerun-if-changed=private/surat.txt");
    let text = std::fs::read_to_string(source).unwrap_or_default();
    let Ok(out_dir) = std::env::var("OUT_DIR") else {
        return;
    };
    let target = Path::new(&out_dir).join("letter.txt");
    if std::fs::read_to_string(&target).ok().as_deref() != Some(text.as_str()) {
        let _ = std::fs::write(&target, text);
    }
}

/// Bump when the conversion settings change so cached outputs are redone.
const MEDIA_VERSION: u32 = 1;
const VIDEO_FPS: u32 = 24;
const VIDEO_HEIGHT: u32 = 432;
const VIDEO_JPEG_QUALITY: u32 = 10;

/// Generates `$OUT_DIR/gift_media.rs` with `TRUMPET` and `VIDEOS` pointing at
/// converted media (both empty in public builds or when ffmpeg is missing).
fn embed_gift_media() {
    let Ok(out_dir) = std::env::var("OUT_DIR") else {
        return;
    };
    let out = PathBuf::from(out_dir);
    println!("cargo:rerun-if-changed=private/video");

    let mut trumpet = None;
    if let Some(src) = find_trumpet() {
        println!("cargo:rerun-if-changed={}", src.display());
        let dst = out.join(format!("gift_trumpet_v{MEDIA_VERSION}.ogg"));
        if fresh(&src, &dst) || convert_audio(&src, &dst) {
            trumpet = Some(dst);
        }
    }

    let mut videos = Vec::new();
    let mut sources: Vec<PathBuf> = std::fs::read_dir("private/video")
        .map(|dir| {
            dir.filter_map(|e| e.ok().map(|e| e.path()))
                .filter(|p| p.is_file())
                .collect()
        })
        .unwrap_or_default();
    sources.sort();
    for (i, src) in sources.iter().enumerate() {
        println!("cargo:rerun-if-changed={}", src.display());
        let frames = out.join(format!("gift_video{i}_v{MEDIA_VERSION}.frames"));
        let audio = out.join(format!("gift_video{i}_v{MEDIA_VERSION}.ogg"));
        let ok_frames = fresh(src, &frames) || convert_frames(src, &frames);
        let ok_audio = fresh(src, &audio) || convert_audio(src, &audio);
        if ok_frames && ok_audio {
            videos.push((display_name(src), frames, audio));
        }
    }

    let mut code = String::from("// Generated by build.rs.\n");
    match &trumpet {
        Some(p) => {
            code += &format!("pub const TRUMPET: Option<&[u8]> = Some(include_bytes!({p:?}));\n")
        }
        None => code += "pub const TRUMPET: Option<&[u8]> = None;\n",
    }
    code += "pub const VIDEOS: &[GiftVideo] = &[\n";
    for (name, frames, audio) in &videos {
        code += &format!(
            "    GiftVideo {{ name: {name:?}, frames: include_bytes!({frames:?}), audio: include_bytes!({audio:?}) }},\n"
        );
    }
    code += "];\n";
    let target = out.join("gift_media.rs");
    if std::fs::read_to_string(&target).ok().as_deref() != Some(code.as_str()) {
        let _ = std::fs::write(&target, code);
    }
}

fn find_trumpet() -> Option<PathBuf> {
    std::fs::read_dir("private")
        .ok()?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .find(|p| p.is_file() && p.file_stem().is_some_and(|s| s == "terompet"))
}

/// "1-Kodok.mp4" -> "Kodok": the number only sets the order.
fn display_name(path: &Path) -> String {
    let stem = path
        .file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_default();
    let trimmed = stem.trim_start_matches(|c: char| {
        c.is_ascii_digit() || c == '-' || c == '_' || c == ' ' || c == '.'
    });
    if trimmed.is_empty() {
        stem
    } else {
        trimmed.to_string()
    }
}

/// True when `dst` exists and is newer than `src` (conversion can be skipped).
fn fresh(src: &Path, dst: &Path) -> bool {
    let modified = |p: &Path| std::fs::metadata(p).and_then(|m| m.modified()).ok();
    matches!((modified(src), modified(dst)), (Some(s), Some(d)) if d >= s)
}

fn ffmpeg(args: &[&str]) -> bool {
    match Command::new("ffmpeg")
        .args(["-v", "error", "-y"])
        .args(args)
        .status()
    {
        Ok(status) if status.success() => true,
        Ok(status) => {
            println!("cargo:warning=ffmpeg failed ({status}) for gift media");
            false
        }
        Err(e) => {
            println!("cargo:warning=ffmpeg not found, gift media skipped: {e}");
            false
        }
    }
}

/// Audio track to Ogg Vorbis (gapless, so the trumpet loops cleanly).
fn convert_audio(src: &Path, dst: &Path) -> bool {
    let (Some(s), Some(d)) = (src.to_str(), dst.to_str()) else {
        return false;
    };
    ffmpeg(&[
        "-i",
        s,
        "-vn",
        "-ac",
        "2",
        "-ar",
        "48000",
        "-c:a",
        "libvorbis",
        "-q:a",
        "5",
        "-f",
        "ogg",
        d,
    ])
}

/// Video track to an indexed JPEG frame pack:
/// `b"FSV1"`, fps (u32 LE), frame count n (u32 LE), n+1 offsets (u32 LE,
/// relative to the data start), then the JPEG data.
fn convert_frames(src: &Path, dst: &Path) -> bool {
    let (Some(s), Some(_)) = (src.to_str(), dst.to_str()) else {
        return false;
    };
    let mjpeg = dst.with_extension("mjpeg");
    let Some(m) = mjpeg.to_str() else {
        return false;
    };
    let filter = format!("fps={VIDEO_FPS},scale=-2:{VIDEO_HEIGHT}:flags=lanczos");
    let quality = VIDEO_JPEG_QUALITY.to_string();
    if !ffmpeg(&[
        "-i",
        s,
        "-an",
        "-vf",
        &filter,
        "-c:v",
        "mjpeg",
        "-q:v",
        &quality,
        "-f",
        "image2pipe",
        m,
    ]) {
        return false;
    }
    let Ok(data) = std::fs::read(&mjpeg) else {
        return false;
    };
    let _ = std::fs::remove_file(&mjpeg);
    // Each frame starts with SOI (FF D8) and ends with EOI (FF D9); inside the
    // entropy-coded data 0xFF is byte-stuffed, and requiring the next frame's
    // SOI right after guards against FF D9 appearing in header tables.
    let mut offsets = vec![0u32];
    let mut i = 0;
    while i + 1 < data.len() {
        let next_is_frame = data.len() == i + 2 || data[i + 2..].starts_with(&[0xFF, 0xD8]);
        if data[i] == 0xFF && data[i + 1] == 0xD9 && next_is_frame {
            offsets.push((i + 2) as u32);
            i += 2;
        } else {
            i += 1;
        }
    }
    if offsets.len() < 2 {
        println!("cargo:warning=no frames decoded from {s}");
        return false;
    }
    let count = offsets.len() as u32 - 1;
    let mut pack = Vec::with_capacity(data.len() + offsets.len() * 4 + 12);
    pack.extend_from_slice(b"FSV1");
    pack.extend_from_slice(&VIDEO_FPS.to_le_bytes());
    pack.extend_from_slice(&count.to_le_bytes());
    for o in &offsets {
        pack.extend_from_slice(&o.to_le_bytes());
    }
    pack.extend_from_slice(&data[..*offsets.last().unwrap_or(&0) as usize]);
    std::fs::write(dst, pack).is_ok()
}
